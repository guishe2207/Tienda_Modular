-- Migración no destructiva: conserva administradores existentes y nunca crea admins públicos.
CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario VARCHAR(60) NOT NULL UNIQUE CHECK (length(trim(usuario)) > 0),
  password_hash TEXT NOT NULL,
  rol VARCHAR(20) NOT NULL CHECK (rol IN ('admin', 'cliente')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
INSERT INTO usuarios (id_usuario, usuario, password_hash, rol, creado_en)
SELECT id_usuario, usuario, password_hash, 'admin', creado_en FROM usuarios_admin
ON CONFLICT (usuario) DO NOTHING;
SELECT setval(pg_get_serial_sequence('usuarios', 'id_usuario'), COALESCE((SELECT MAX(id_usuario) FROM usuarios), 1), true);
CREATE TABLE IF NOT EXISTS sesiones_usuario (
  token_hash CHAR(64) PRIMARY KEY,
  id_usuario INTEGER NOT NULL REFERENCES usuarios (id_usuario) ON DELETE CASCADE,
  expira_en TIMESTAMPTZ NOT NULL
);
ALTER TABLE pedidos ADD COLUMN IF NOT EXISTS id_usuario INTEGER REFERENCES usuarios (id_usuario) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_pedidos_usuario ON pedidos (id_usuario, fecha_creacion DESC);
