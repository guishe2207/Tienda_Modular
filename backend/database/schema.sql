CREATE TABLE IF NOT EXISTS categorias (
  id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL CHECK (length(trim(nombre)) > 0),
  descripcion TEXT
);

CREATE TABLE IF NOT EXISTS productos (
  id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL CHECK (length(trim(nombre)) > 0),
  descripcion TEXT,
  precio NUMERIC(12, 2) NOT NULL CHECK (precio > 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  imagen TEXT,
  id_categoria INTEGER NOT NULL,
  CONSTRAINT fk_productos_categoria
    FOREIGN KEY (id_categoria)
    REFERENCES categorias (id_categoria)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_productos_id_categoria ON productos (id_categoria);

CREATE TABLE IF NOT EXISTS usuarios_admin (
  id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario VARCHAR(60) NOT NULL UNIQUE CHECK (length(trim(usuario)) > 0),
  password_hash TEXT NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Identidades de la aplicación. Los administradores se crean únicamente con scripts internos.
CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario VARCHAR(60) NOT NULL UNIQUE CHECK (length(trim(usuario)) > 0),
  password_hash TEXT NOT NULL,
  rol VARCHAR(20) NOT NULL CHECK (rol IN ('admin', 'cliente')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sesiones_admin (
  token_hash CHAR(64) PRIMARY KEY,
  id_usuario INTEGER NOT NULL REFERENCES usuarios_admin (id_usuario) ON DELETE CASCADE,
  expira_en TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS sesiones_usuario (
  token_hash CHAR(64) PRIMARY KEY,
  id_usuario INTEGER NOT NULL REFERENCES usuarios (id_usuario) ON DELETE CASCADE,
  expira_en TIMESTAMPTZ NOT NULL
);

-- El historial conserva el nombre y precio aunque el producto cambie después.
CREATE TABLE IF NOT EXISTS pedidos (
  id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_cliente VARCHAR(160) NOT NULL,
  correo VARCHAR(254) NOT NULL,
  telefono VARCHAR(40) NOT NULL,
  direccion TEXT NOT NULL,
  ciudad VARCHAR(120) NOT NULL,
  departamento VARCHAR(120) NOT NULL,
  observaciones TEXT,
  total NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
  estado VARCHAR(30) NOT NULL DEFAULT 'CONFIRMADO',
  clave_idempotencia UUID NOT NULL UNIQUE,
  id_usuario INTEGER REFERENCES usuarios (id_usuario) ON DELETE SET NULL,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS detalle_pedido (
  id_detalle INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido INTEGER NOT NULL REFERENCES pedidos (id_pedido) ON DELETE RESTRICT,
  id_producto INTEGER NOT NULL REFERENCES productos (id_producto) ON DELETE RESTRICT,
  nombre_producto VARCHAR(120) NOT NULL,
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  precio_unitario NUMERIC(12, 2) NOT NULL CHECK (precio_unitario > 0),
  subtotal NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0)
);
CREATE INDEX IF NOT EXISTS idx_detalle_pedido_pedido ON detalle_pedido (id_pedido);
CREATE INDEX IF NOT EXISTS idx_pedidos_fecha ON pedidos (fecha_creacion DESC);
